const DAYS = ['2026-08-18', '2026-08-19', '2026-08-20', '2026-08-21', '2026-08-22', '2026-08-23', '2026-08-24'];
const SLOTS = ['00:00', '09:00', '12:00', '15:00', '18:00', '21:00'];

// สร้างรายการสินค้าตัวอย่างพร้อมรอบดีล (ค่าเริ่มต้น 7 วัน × 4 รอบ)
export function buildShopeeSample(seed = 20260818) {
  const rand = rng(seed);
  const now = new Date().toISOString();

  return CATALOG.map(([name, category, listPrice], i) => {
    const shopName = SHOPS[i % SHOPS.length];
    const discount = Math.round(15 + rand() * 65);           // 15–80%
    const price = Math.max(9, Math.round((listPrice * (100 - discount)) / 100));
    const roundCount = 1 + Math.floor(rand() * 4);           // 1–4 รอบ
    const rounds = [];
    for (let r = 0; r < roundCount; r += 1) {
      const day = DAYS[Math.floor(rand() * DAYS.length)];
      const slot = SLOTS[Math.floor(rand() * SLOTS.length)];
      const start = `${day}T${slot}`;
      if (!rounds.some((x) => x.start === start)) rounds.push({ start, end: null });
    }
    const rating = Math.round((3.4 + rand() * 1.6) * 10) / 10;

    return normalizeProduct({
      itemId: `1000${i}`,
      shopId: `90${i % SHOPS.length}`,
      name,
      shopName,
      category,
      price,
      originalPrice: listPrice,
      discountPct: discount,
      commissionRate: Math.round((2 + rand() * 10) * 10) / 10,
      rating,
      ratingCount: Math.round(rand() * 4000),
      sold: Math.round(rand() * 20000),
      stock: Math.round(rand() * 900),
      url: `https://shopee.co.th/product/90${i % SHOPS.length}/1000${i}`,
      rounds,
    }, { source: 'ตัวอย่าง', importedAt: now });
  });
}
